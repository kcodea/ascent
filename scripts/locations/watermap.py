"""The water map of each location (water.webp): R = falling water, G = a flat surface, B = across the stream (0 left edge .. 1 right).
Traced on the owner's paintings on a 1886 x 800 grid. Falls follow their own two edges, so the streaks run down the stream.
python scripts/locations/watermap.py [proof-dir]   (from the repo root; see docs/locations.md)"""
import sys
import numpy as np
from PIL import Image, ImageDraw
from scipy.ndimage import gaussian_filter

GW, GH, S = 1886, 800, 2
PUB = 'apps/web/public/locations/'


def poly(polys, feather):
    im = Image.new('L', (GW * S, GH * S), 0)
    d = ImageDraw.Draw(im)
    for p in polys:
        d.polygon([(x * S, y * S) for x, y in p], fill=255)
    return gaussian_filter(np.asarray(im, float) / 255, feather * S) if feather else np.asarray(im, float) / 255


def falls(list_):
    yy, xx = np.mgrid[0:GH * S, 0:GW * S] / S
    R, B, near = np.zeros_like(xx), np.full_like(xx, .5), np.full_like(xx, 1e9)
    for left, right, top, bot, k in list_:
        l = np.interp(yy, [p[1] for p in left], [p[0] for p in left])
        r = np.interp(yy, [p[1] for p in right], [p[0] for p in right])
        w = np.maximum(r - l, 1)
        u = (xx - l) / w
        y0, y1 = min(left[0][1], right[0][1]), max(left[-1][1], right[-1][1])
        edge = np.clip(np.minimum(u, 1 - u) / .14 + .25, 0, 1)
        a = edge * np.clip((yy - y0) / max(top, .01), 0, 1) * np.clip((y1 - yy) / max(bot, .01), 0, 1) * k
        a[(u < -.04) | (u > 1.04) | (yy < y0) | (yy > y1)] = 0
        far = np.maximum(np.maximum(l - xx, xx - r), np.maximum(y0 - yy, yy - y1))
        take = far < near
        near = np.where(take, far, near)
        B = np.where(take, np.clip(u, 0, 1), B)
        R = np.maximum(R, a)
    return R, B


def make(folder, streams, pools, excl, excl_falls):
    R, B = falls(streams)
    if excl_falls:
        R *= 1 - poly(excl_falls, .6)
    hole = np.maximum(poly(pools, 0) * 0, poly(excl, 0)) if excl else 0
    G = gaussian_filter(np.clip(poly(pools, 0) - hole, 0, 1), 1.6 * S)
    G = np.clip((G - .5) * 2, 0, 1)          # only ever inside the water: what stands in it never moves
    G = gaussian_filter(G, .8 * S) * (1 - np.clip(R * 1.5, 0, 1))
    out = np.dstack([gaussian_filter(R, .6 * S), G, B])
    Image.fromarray(np.uint8(np.clip(out, 0, 1) * 255)).resize((GW, GH), Image.LANCZOS).save(PUB + folder + '/water.webp', lossless=True, method=6)
    if len(sys.argv) > 1:
        f = np.asarray(Image.open(PUB + folder + '/flat.webp').convert('RGB').resize((GW, GH)), float)
        w = np.asarray(Image.open(PUB + folder + '/water.webp').convert('RGB'), float) / 255
        p = f * (1 - .75 * np.maximum(w[..., :1], w[..., 1:2])) + 190 * np.dstack([w[..., 0], w[..., 1] * .2, w[..., 1]]) + 60 * np.dstack([0 * w[..., 0], w[..., 0] * np.round(w[..., 2] * 4) / 4, 0 * w[..., 0]])
        Image.fromarray(np.uint8(np.clip(p, 0, 255))).save(sys.argv[1] + '/water-' + folder + '.png')


