/**
 * `npm run versus:bundle`: build the Versus resolver's Deno bundle (blueprint 4.1, Phase 0).
 *
 * The `versus-resolve` Edge Function must run the EXACT `@game/core` + `@game/content` combat the client runs, so
 * it imports one esbuild bundle of `packages/sim/src/versus/server.ts` (core + content + the pure Versus resolver,
 * no reducer, no UI): `supabase/functions/versus-resolve/engine.generated.js`. The file is GENERATED and
 * gitignored (~1.5 MB, and it changes with every content edit): build it right before every deploy.
 *
 *     npm run versus:bundle && npx supabase functions deploy versus-resolve --no-verify-jwt
 *
 * `platform: 'neutral'` means a Node built-in reaching the bundle fails the build instead of the deploy.
 */
import { execSync } from 'node:child_process';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { contentRevision } from '@game/content';
import { VERSUS_PROTOCOL } from '@game/sim';

const root = join(fileURLToPath(new URL('.', import.meta.url)), '../../..');
export const VERSUS_BUNDLE_PATH = join(root, 'supabase/functions/versus-resolve/engine.generated.js');

function gitSha(): string {
  try {
    return execSync('git rev-parse --short HEAD', { cwd: root }).toString().trim();
  } catch {
    return 'unknown';
  }
}

export async function buildVersusBundle(outfile = VERSUS_BUNDLE_PATH): Promise<void> {
  await build({
    entryPoints: [join(root, 'packages/sim/src/versus/server.ts')],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    mainFields: ['module', 'main'],
    outfile,
    logLevel: 'warning',
    legalComments: 'none',
    banner: {
      js: [
        '// GENERATED by `npm run versus:bundle` (packages/tools/src/versus-bundle.ts). Do not edit, do not commit.',
        `// source ${gitSha()} · content ${contentRevision()} · protocol ${VERSUS_PROTOCOL}`,
        '// @ts-nocheck',
      ].join('\n'),
    },
  });
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await buildVersusBundle();
  console.log(`wrote ${VERSUS_BUNDLE_PATH} (content ${contentRevision()}, protocol ${VERSUS_PROTOCOL})`);
}
