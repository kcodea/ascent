/**
 * GUIDES: the text of packages/ui/src/guides/guides.bundled.ts, made from the live Team Ascent guides
 * (spec section 6: "Keeping the fallback fresh"). `npm run guides:pull` (packages/tools/src/guides-pull.ts) reads
 * the guides and writes what `renderBundledGuides` returns.
 *
 * Pure and dependency-free. NOT exported from index.ts and NOT one of the generated Deno copies: only the script and
 * its tests use it. The output is plain ASCII (anything else is written as an escape), so the file never depends on
 * how an editor saves it.
 */
import type { GuideRecord } from './types';

export interface BundledSourceGuide {
  id: string;
  set: string;
  tribes: string[];
  pairsWith: string[];
  iconCard: string;
  title: string;
  tagline: string;
  body: string;
  core: string[];
  enablers: string[];
  mentions: string[];
  aliases: Record<string, string>;
}

/** The Team Ascent guides, in their order, as the built-in file holds them. A guide with no set cannot be shown and is left out. */
export function recordsToBundled(records: readonly GuideRecord[]): BundledSourceGuide[] {
  return records
    .filter((r) => r.official && r.sets.length > 0)
    .slice()
    .sort((a, b) => a.sortOrder - b.sortOrder || a.id.localeCompare(b.id))
    .map((r) => ({
      id: r.slug ?? r.id, set: r.sets[0]!, tribes: [...r.tribes], pairsWith: [...r.pairsWith], iconCard: r.iconCard, title: r.title, tagline: r.tagline,
      body: r.body, core: [...r.core], enablers: [...r.enablers], mentions: [...r.mentions], aliases: { ...r.aliases },
    }));
}

const BACKSLASH = String.fromCharCode(92);
const hex4 = (n: number): string => n.toString(16).padStart(4, '0');

/** A single-quoted TypeScript string literal, plain ASCII. */
function quote(s: string): string {
  let out = "'";
  for (let i = 0; i < s.length; i++) {
    const code = s.charCodeAt(i);
    const ch = s[i]!;
    if (ch === BACKSLASH) out += BACKSLASH + BACKSLASH;
    else if (ch === "'") out += BACKSLASH + "'";
    else if (code < 32 || code > 126) out += `${BACKSLASH}u${hex4(code)}`;
    else out += ch;
  }
  return `${out}'`;
}
const list = (xs: readonly string[]): string => `[${xs.map(quote).join(', ')}]`;

