/**
 * The v2 backfill as pure functions (strength v2 design 2026-11-16, "Transition"): every pool board's score is
 * REPLACED by its v2 score, and each run's final board gains its carried scores. The CLI writes the text to a file
 * an owner runs; nothing here touches the backend.
 */

/** What a run's final board carries: its raw score at every round it never reached, up to the last reference
 *  round, stamped with the reference version (stored as `boards.strength_carried`). */
export interface CarriedScores { ref: string; rounds: Record<string, number> }

export interface BackfillRow {
  /** `boards.id`. */
  rowId: string;
  /** Raw win rate at the board's own round; null for an empty board (it is raw 0 and never fought). */
  raw: number | null;
  /** The reference round it was scored against; null with no score. */
  refWave: number | null;
  /** Only on the rows of the run's final round. */
  carried: CarriedScores | null;
}

/**
 * One run's rows. `score(boardWave, atRound)` fights the board recorded at `boardWave` against the reference of
 * `atRound` (null when it cannot be scored). Every row of the final round gets the carried map, so whichever row
 * the database takes for that round has it.
 */
export function backfillRowsOfRun(
  boards: readonly { rowId: string; wave: number; minions: number }[], lastRefRound: number, version: string,
  score: (boardWave: number, atRound: number) => { raw: number; refWave: number } | null,
): BackfillRow[] {
  if (!boards.length) return [];
  const last = boards.reduce((m, b) => Math.max(m, b.wave), 0);
  const firstAt = new Map<number, { minions: number }>();
  for (const b of boards) if (!firstAt.has(b.wave)) firstAt.set(b.wave, b);
  const own = new Map<number, { raw: number; refWave: number } | null>();
  for (const [wave, b] of firstAt) own.set(wave, b.minions > 0 ? score(wave, wave) : null);
  const rounds: Record<string, number> = {};
  for (let round = last + 1; round <= lastRefRound; round++) {
    rounds[String(round)] = firstAt.get(last)!.minions > 0 ? score(last, round)?.raw ?? 0 : 0;
  }
  return boards.map((b) => {
    const s = own.get(b.wave) ?? null;
    return { rowId: b.rowId, raw: s?.raw ?? null, refWave: s?.refWave ?? null, carried: b.wave === last ? { ref: version, rounds } : null };
  });
}

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/** The SQL file: one transaction, one UPDATE of `public.boards`. Run it right after the strength v2 migration. */
export function backfillV2Sql(version: string, rows: readonly BackfillRow[]): string {
  if (!/^[a-z0-9-]+$/.test(version)) throw new Error(`unexpected reference version: ${version}`);
  const value = (r: BackfillRow): string => {
    if (!UUID.test(r.rowId)) throw new Error(`not a uuid: ${r.rowId}`);
    const num = (x: number | null): string => (x === null ? 'null' : String(Number(x)));
    const carried = r.carried === null ? 'null' : `'${JSON.stringify({ ref: r.carried.ref, rounds: r.carried.rounds }).replace(/'/g, "''")}'`;
    return `  ('${r.rowId}'::uuid, ${num(r.raw)}, ${num(r.refWave)}, ${carried})`;
  };
  return [
    '-- STRENGTH V2 BACKFILL (2026-11-16). Generated by `npm run strength -- backfill`; do not edit.',
    `-- Reference ${version}. Run in the SAME transaction as, and right after, supabase/migrations/2026-11-23-strength-v2.sql,`,
    '-- then `select public.pool_refresh_dirty();`. It REPLACES every listed board\'s score.',
    'begin;',
    '-- Each value is (boards.id, raw win rate, reference round, carried scores of the final board).',
    `update public.boards b set strength_raw = v.raw::numeric, strength_ref = case when v.raw is null then null else '${version}' end,`,
    '  strength_wave = v.wave::smallint, strength_carried = v.carried::jsonb',
    'from (values',
    rows.map(value).join(',\n'),
    ') as v(id, raw, wave, carried)',
    'where b.id = v.id;',
    'commit;',
    '',
  ].join('\n');
}
