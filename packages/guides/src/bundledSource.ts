/**
 * What is wrong with the server's answer, as sentences naming the guides (ids are not private). Empty when the answer
 * can be written. `rows` is the raw answer and `records` what `parseGuideRecord` made of it. The script writes nothing
 * unless this is empty, so a guide can never go missing from the fallback without anyone hearing of it.
 */
export function pullProblems(rows: readonly unknown[], records: readonly GuideRecord[]): string[] {
  const problems: string[] = [];
  const rowId = (r: unknown): string | null =>
    typeof r === 'object' && r !== null && typeof (r as { id?: unknown }).id === 'string' ? (r as { id: string }).id : null;
  const kept = new Set(records.map((r) => r.id));
  const unread = rows.filter((r) => { const id = rowId(r); return id === null || !kept.has(id); });
  if (unread.length > 0) {
    problems.push(`${unread.length} of ${rows.length} guides could not be read: ${unread.map((r) => rowId(r) ?? '(no id)').join(', ')}`);
  }
  const noSet = records.filter((r) => r.official && r.sets.length === 0).map((r) => r.slug ?? r.id);
  if (noSet.length > 0) problems.push(`${noSet.length} Team Ascent guides are in no set, so they could not be shown: ${noSet.join(', ')}`);
  return problems;
}

/** The total after the slash of a Content-Range header ("0-10/11", "*" + "/0"), or null when it is missing or unreadable. */
export function contentRangeTotal(header: string | null | undefined): number | null {
  const m = /^(?:[0-9]+-[0-9]+|[*])[/]([0-9]+)$/.exec((header ?? '').trim());
  return m ? Number(m[1]) : null;
}

export function renderBundledGuides(guides: readonly BundledSourceGuide[]): string {
  const entries = guides.map((g) => {
    const lines = [
      '  {',
      `    id: ${quote(g.id)},`,
      `    iconCard: ${quote(g.iconCard)},`,
      `    set: ${quote(g.set)},`,
      `    tribes: ${list(g.tribes)},`,
    ];
    if (g.pairsWith.length > 0) lines.push(`    pairsWith: ${list(g.pairsWith)},`);
    lines.push(`    title: ${quote(g.title)},`, `    tagline: ${quote(g.tagline)},`, `    body: ${quote(g.body)},`, `    core: ${list(g.core)},`, `    enablers: ${list(g.enablers)},`);
    if (g.mentions.length > 0) lines.push(`    mentions: ${list(g.mentions)},`);
    const names = Object.keys(g.aliases);
    if (names.length > 0) lines.push(`    aliases: { ${names.map((k) => `${quote(k)}: ${quote(g.aliases[k]!)}`).join(', ')} },`);
    lines.push('  },');
    return lines.join('\n');
  });
  return `${HEADER}\n${entries.join('\n')}\n];\n`;
}
